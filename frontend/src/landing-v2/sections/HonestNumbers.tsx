import { motion, useInView } from "motion/react";
import { useRef } from "react";
import { useCountUp, useReducedMotionPref } from "../lib/hooks";

function Bar({ label, value, max, text, tone, run }: { label: string; value: number; max: number; text: string; tone: string; run: boolean }) {
  return (
    <div className="grid grid-cols-[7.5rem_1fr_auto] items-center gap-3 sm:grid-cols-[9.5rem_1fr_4.5rem]">
      <span className="text-[0.9rem] font-semibold">{label}</span>
      <span className="relative h-4 overflow-hidden rounded-full bg-ink/10">
        <motion.span
          className={`absolute inset-y-0 left-0 rounded-full ${tone}`}
          initial={false}
          animate={{ width: run ? `${(value / max) * 100}%` : "0%" }}
          transition={{ duration: 1.1, ease: [0.2, 0.8, 0.2, 1] }}
        />
      </span>
      <span className="text-right font-mono text-[0.95rem] font-semibold">{text}</span>
    </div>
  );
}

export function HonestNumbers() {
  const ref = useRef<HTMLDivElement>(null);
  const inView = useInView(ref, { once: true, amount: 0.3 });
  const reduced = useReducedMotionPref();
  const run = inView || reduced;
  const found = useCountUp(42, run, 0, 1300, reduced);
  const secs = useCountUp(1.1, run, 1, 1300, reduced);

  return (
    <section id="numbers" aria-labelledby="numbers-title" className="on-dark bg-ink px-5 py-24 text-white sm:px-10 sm:py-32">
      <div className="mx-auto max-w-[1400px]">
        <div className="grid gap-6 lg:grid-cols-[1.1fr_1fr] lg:items-end">
          <h2 id="numbers-title" className="font-display text-[clamp(2.4rem,5vw,4.8rem)] leading-[0.98] font-[800]">
            Honest numbers.
          </h2>
          <p className="max-w-[36rem] text-[1.1rem] leading-relaxed text-white/85">
            Measured on synthetic data generated by the team: an upper bound.
          </p>
        </div>

        <div ref={ref} className="mt-12 grid gap-4 md:grid-cols-6">
          <div className="rounded-[32px] bg-sun p-7 text-ink md:col-span-2 sm:p-8">
            <p className="font-display leading-none font-[800]" aria-label="42 of 42">
              <span aria-hidden className="text-[clamp(3.6rem,6vw,5.4rem)] tabular-nums">
                {found}
              </span>
              <span aria-hidden className="ml-2 text-[1.6rem] font-[650]">
                of 42
              </span>
            </p>
            <p className="mt-4 text-[1.05rem] leading-snug font-semibold">
              planted conditions found on 11 synthetic applications.
            </p>
          </div>
          <div className="rounded-[32px] bg-rose p-7 text-ink md:col-span-2 sm:p-8">
            <p className="font-display text-[clamp(3.6rem,6vw,5.4rem)] leading-none font-[800]">0</p>
            <p className="mt-4 text-[1.05rem] leading-snug font-semibold">false alarms on benign controls.</p>
          </div>
          <div className="rounded-[32px] bg-tang p-7 text-ink md:col-span-2 sm:p-8">
            <p className="font-display leading-none font-[800]" aria-label="About 1.1 seconds">
              <span aria-hidden className="mr-2 text-[1.6rem] font-[650]">
                about
              </span>
              <span aria-hidden className="text-[clamp(3.6rem,6vw,5.4rem)] tabular-nums">
                {secs}
              </span>
              <span aria-hidden className="ml-1 text-[1.6rem] font-[650]">
                s
              </span>
            </p>
            <p className="mt-4 text-[1.05rem] leading-snug font-semibold">per validation.</p>
          </div>

          <div className="rounded-[32px] bg-cream p-7 text-ink md:col-span-6 sm:p-10">
            <div className="grid gap-8 lg:grid-cols-[0.9fr_1.4fr] lg:gap-14">
              <div>
                <p className="text-[0.8rem] font-bold tracking-[0.14em] text-ink-2 uppercase">The local extractor</p>
                <h3 className="mt-2 font-display text-[clamp(1.7rem,2.6vw,2.4rem)] leading-[1.05] font-[760]">
                  A fine-tuned 1.7B model that runs locally, against a general 4B model.
                </h3>
                <p className="mt-3 text-[1rem] leading-relaxed text-ink-2">
                  On 200 unseen layouts. The smaller model is also the faster one: half the latency.
                </p>
              </div>
              <div className="grid content-center gap-7">
                <div>
                  <p className="mb-3 text-[0.95rem] font-bold">Fields fully correct</p>
                  <div className="grid gap-2.5">
                    <Bar label="Fine-tuned 1.7B" value={92} max={100} text="92%" tone="bg-ok" run={run} />
                    <Bar label="General 4B" value={83} max={100} text="83%" tone="bg-ink/55" run={run} />
                  </div>
                </div>
                <div>
                  <p className="mb-3 text-[0.95rem] font-bold">
                    Planted instructions followed <span className="font-medium text-ink-2">(lower is better)</span>
                  </p>
                  <div className="grid gap-2.5">
                    <Bar label="Fine-tuned 1.7B" value={1} max={30} text="1 of 30" tone="bg-ok" run={run} />
                    <Bar label="General 4B" value={9} max={30} text="9 of 30" tone="bg-alert" run={run} />
                  </div>
                </div>
                <div>
                  <p className="mb-3 text-[0.95rem] font-bold">Latency, relative</p>
                  <div className="grid gap-2.5">
                    <Bar label="Fine-tuned 1.7B" value={1} max={2} text="0.5x" tone="bg-ok" run={run} />
                    <Bar label="General 4B" value={2} max={2} text="1x" tone="bg-ink/55" run={run} />
                  </div>
                </div>
              </div>
            </div>
          </div>
        </div>
      </div>
    </section>
  );
}
