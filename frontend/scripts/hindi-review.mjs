// Writes every English and Hindi pair in src/i18n/hi.ts as a Markdown table for proofreading.
// Usage: node scripts/hindi-review.mjs <output.md>
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const out = process.argv[2];
if (!out) {
  console.error("Usage: node scripts/hindi-review.mjs <output.md>");
  process.exit(1);
}

const src = readFileSync(join(dirname(fileURLToPath(import.meta.url)), "..", "src", "i18n", "hi.ts"), "utf8");
const start = src.indexOf("export const HI");
if (start < 0) throw new Error("HI dictionary not found in src/i18n/hi.ts");
const body = src.slice(src.indexOf("{", start) + 1, src.lastIndexOf("};"));

// A group comment on its own line, or a "key": "value" pair that may wrap onto the next line
const token = /^\s*\/\/\s*(.+)$|("(?:[^"\\]|\\.)*")\s*:\s*("(?:[^"\\]|\\.)*")/gm;
const groups = [];
let group = { name: "General", rows: [] };
for (let m = token.exec(body); m; m = token.exec(body)) {
  if (m[1] !== undefined) {
    if (group.rows.length) groups.push(group);
    group = { name: m[1].trim(), rows: [] };
  } else {
    group.rows.push([JSON.parse(m[2]), JSON.parse(m[3])]);
  }
}
if (group.rows.length) groups.push(group);

// "Change@@verb" is the key for one of two Hindi words for the same English; show the context in brackets
const english = (k) => {
  const i = k.indexOf("@@");
  return i < 0 ? k : `${k.slice(0, i)} [${k.slice(i + 2)}]`;
};
const cell = (s) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

const total = groups.reduce((n, g) => n + g.rows.length, 0);
const lines = [
  "# Pramana: Hindi strings for review",
  "",
  `Every English and Hindi pair the institution portal and the sign-in page use, ${total} in all, grouped by screen.`,
  "Officials' screens stay in English. Text the server sends also stays in English in both languages: letter items,",
  "officers' reasons, the scrutiny outcome wording, notification bodies, checklist document names and error messages.",
  "Words in curly brackets such as {n} or {date} are filled in by the app; keep them as they are.",
  "",
  "To correct a translation, edit the Hindi value for that English key in `frontend/src/i18n/hi.ts`, or send the row",
  "number with the corrected Hindi to the team. This file is generated by `node scripts/hindi-review.mjs <output.md>`",
  "from that file, so do not edit it by hand.",
  "",
];
let n = 0;
for (const g of groups) {
  lines.push(`## ${g.name}`, "", "| # | English | Hindi | Where |", "| ---: | --- | --- | --- |");
  for (const [k, v] of g.rows) lines.push(`| ${++n} | ${cell(english(k))} | ${cell(v)} | ${cell(g.name)} |`);
  lines.push("");
}
writeFileSync(out, lines.join("\n"), "utf8");
console.log(`Wrote ${n} pairs in ${groups.length} groups to ${out}`);
